/// Where an item that lies on the ground is: a charm (`gotCharm_5`) or an
/// ability (`hasDash`), from the shiny thing that gives it.
pub fn item_spot(key: &str) -> Option<(&'static str, f32, f32)> {
    let shiny = SHINIES.iter().find(|x| {
        x.4 == key || key.strip_prefix("gotCharm_").and_then(|n| n.parse::<u8>().ok()).is_some_and(|n| x.3 == n && x.2 == 0)
    })?;
    PICKUPS.iter().find(|p| p.scene == shiny.0 && p.id == shiny.1).map(|p| (p.scene, p.x, p.y))
}

impl Kind {
    pub fn label(self, fr: bool) -> &'static str {
        match (self, fr) {
            (Kind::Mask, true) => "Fragment de masque",
            (Kind::Mask, false) => "Mask shard",
            (Kind::Vessel, true) => "Fragment de réceptacle",
            (Kind::Vessel, false) => "Vessel fragment",
            (Kind::Chest, true) => "Coffre de géo",
            (Kind::Chest, false) => "Geo chest",
            (Kind::Rock, true) => "Rocher de géo",
            (Kind::Rock, false) => "Geo rock",
            (Kind::Shiny, true) => "Objet au sol",
            (Kind::Shiny, false) => "Item on the ground",
        }
    }

}

