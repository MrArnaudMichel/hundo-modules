/// The item a pickup stands for, by id.
pub fn item_id(p: &P) -> String {
    format!("pick-{}-{}", p.scene, p.id)
}

impl Analysis<'_> {
    /// Whether the save has a room's object taken, opened or broken.
    fn taken(&self, p: &P) -> bool {
        // Every shard found: the save keeps no trace of some of them (the
        // stag nest's fragment), but the totals say they are all taken.
        match p.kind {
            Kind::Mask if self.int("maxHealthBase") >= 9 => return true,
            Kind::Vessel if self.int("MPReserveMax") >= 99 => return true,
            _ => {}
        }
        let list = |key: &str| self.save_scene_data(key).into_iter().flatten();
        if p.kind == Kind::Rock {
            return list("geoRocks").any(|r| r["sceneName"] == p.scene && r["id"] == p.id && r["hitsLeft"].as_i64() == Some(0));
        }
        list("persistentBoolItems").any(|r| r["sceneName"] == p.scene && r["id"] == p.id && r["activated"] == true)
    }

    /// Every pickup of one kind, each with its room's area.
    pub(crate) fn pickups(&self, kind: Kind, area_of_scene: &dyn Fn(&str) -> Option<String>) -> Vec<Item> {
        PICKUPS
            .iter()
            .filter(|p| p.kind == kind)
            // A shiny thing is listed only when it is known and not already an
            // item of its own (a charm, an ability: those take its spot).
            .filter(|p| kind != Kind::Shiny || SHINIES.iter().any(|x| x.0 == p.scene && x.1 == p.id && x.3 == 0 && !x.4.starts_with("has")))
            .map(|p| {
                let area = area_of_scene(p.scene);
                // A shiny thing by what it is, when the game says.
                let what = SHINIES.iter().find(|x| x.0 == p.scene && x.1 == p.id).and_then(|x| shiny(x.2, x.4, self.fr));
                let label = what.map_or(kind.label(self.fr), |w| w.0);
                let title = match &area {
                    Some(a) => format!("{label} · {}", self.zone(a)),
                    None => label.to_string(),
                };
                let mut item = Item::new(item_id(p), title, if self.taken(p) { Status::Done } else { Status::Todo });
                if let Some((_, picture)) = what {
                    item = item.image(format!("game:{picture}"));
                }
                match kind {
                    Kind::Chest | Kind::Rock => item = item.image("game:InventoryCoin"),
                    Kind::Mask => item = item.image("game:select_game_HUD_0001_health"),
                    Kind::Vessel => item = item.image("game:Inv_0031_inv_soul_piece_full"),
                    _ => {}
                }
                if let Some(a) = area {
                    item = item.location(a);
                }
                item
            })
            .collect()
    }
}
